-- 4. QUEUE TOKENS -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS queue_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  centre_id uuid NOT NULL REFERENCES service_centres(id) ON DELETE CASCADE,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  token_number integer NOT NULL,
  people_ahead integer NOT NULL DEFAULT 0,
  est_wait_minutes integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'called', 'completed', 'cancelled')),
  generated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

ALTER TABLE queue_tokens ENABLE ROW LEVEL SECURITY;

GRANT SELECT, UPDATE ON queue_tokens TO authenticated;

DROP POLICY IF EXISTS "Users can view own tokens" ON queue_tokens;
CREATE POLICY "Users can view own tokens" ON queue_tokens
FOR SELECT TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admins can view all tokens" ON queue_tokens;
CREATE POLICY "Admins can view all tokens" ON queue_tokens
FOR SELECT TO authenticated USING (
  EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin')
);

DROP POLICY IF EXISTS "Users can cancel own token" ON queue_tokens;
CREATE POLICY "Users can cancel own token" ON queue_tokens
FOR UPDATE TO authenticated
USING (auth.uid() = user_id AND status = 'waiting')
WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admins can update any token" ON queue_tokens;
CREATE POLICY "Admins can update any token" ON queue_tokens
FOR UPDATE TO authenticated USING (
  EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin')
) WITH CHECK (
  EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin')
);

-- 5. QUEUE UPDATES ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS queue_updates (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  centre_id uuid NOT NULL REFERENCES service_centres(id) ON DELETE CASCADE,
  token_id uuid REFERENCES queue_tokens(id) ON DELETE SET NULL,
  message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
