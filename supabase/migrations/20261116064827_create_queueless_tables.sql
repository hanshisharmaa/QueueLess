/*
# Create QueueLess core tables

1. New Tables
- `profiles` — extends auth.users with a display name and role (customer | admin). One row per user, created automatically on sign-up by a database trigger.
  - `id` (uuid, PK, references auth.users, defaults to the authenticated user)
  - `email` (text)
  - `full_name` (text)
  - `role` (text, 'customer' or 'admin')
  - `created_at` (timestamp)
- `service_centres` — one row per service centre (clinic, salon, government office, etc.).
  - `id` (uuid, PK)
  - `name`, `category`, `description`, `address`, `city` (text)
  - `image_url` (text) — photo of the centre
  - `avg_service_time` (integer minutes per customer)
  - `is_open` (boolean)
  - `opens_at`, `closes_at` (text, e.g. "08:00")
  - `queue_status` (text: low | moderate | busy)
  - `currently_serving` (integer token number)
  - `created_at` (timestamp)
- `services` — services offered by each centre.
  - `id`, `centre_id` (FK to service_centres, cascade), `name`, `duration_minutes` (integer)
- `queue_tokens` — digital tokens generated by customers.
  - `id`, `centre_id` (FK), `user_id` (uuid, NOT NULL, DEFAULT auth.uid(), FK to auth.users cascade)
  - `token_number` (integer), `people_ahead` (integer), `est_wait_minutes` (integer)
  - `status` (text: waiting | called | completed | cancelled)
  - `generated_at`, `completed_at` (timestamps)
- `queue_updates` — audit trail of queue events (calls, completions, cancellations).
  - `id`, `centre_id` (FK), `token_id` (nullable FK), `message` (text), `created_at`

2. Triggers and Functions
- `handle_new_user()` — SECURITY DEFINER; inserts a `profiles` row for every new sign-up (default role 'customer').
- `generate_token(centre_uuid)` — SECURITY DEFINER, callable only by `authenticated`. Atomically computes the next token number, people ahead and estimated wait, inserts the queue_tokens row, bumps centre queue status if needed, and returns the new token row. Prevents duplicate active tokens at the same centre (raises 'You already have an active token for this centre').
- `is_admin()` — small helper used by RLS to grant admins write access to centres.

3. Security
- RLS ENABLED on all four new tables.
- profiles: users read/update only their own row; everyone can read a profile's role (needed for routing guards? no — restricted to own row only; admins are detected via their own profile).
  Actually policies: SELECT own row only; INSERT handled by trigger (service role); UPDATE own row (full_name only via column grant).
- service_centres: public read (anon + authenticated); write only for admins (via is_admin()).
- services: public read; admin write.
- queue_tokens: users read/update (cancel) only their own tokens; admins full read/update. Insert is done through the `generate_token` SECURITY DEFINER function only.
- queue_updates: authenticated read; service-role/admin write.
- Grants: SELECT/UPDATE per table to the correct roles; EXECUTE on generate_token to authenticated only; revoked from public/anon.
*/

-- 1. PROFILES ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  email text,
  full_name text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

GRANT SELECT, UPDATE (full_name) ON profiles TO authenticated;

DROP POLICY IF EXISTS "Users can view own profile" ON profiles;
CREATE POLICY "Users can view own profile" ON profiles
FOR SELECT TO authenticated USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update own profile" ON profiles;
CREATE POLICY "Users can update own profile" ON profiles
FOR UPDATE TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, role)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', ''),
    COALESCE(NEW.raw_user_meta_data->>'role', 'customer')
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 2. SERVICE CENTRES --------------------------------------------------------
CREATE TABLE IF NOT EXISTS service_centres (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  category text NOT NULL CHECK (category IN ('healthcare', 'beauty', 'government', 'repair', 'banking')),
  description text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '',
  avg_service_time integer NOT NULL DEFAULT 10,
  is_open boolean NOT NULL DEFAULT true,
  opens_at text NOT NULL DEFAULT '08:00',
  closes_at text NOT NULL DEFAULT '18:00',
  queue_status text NOT NULL DEFAULT 'low' CHECK (queue_status IN ('low', 'moderate', 'busy')),
  currently_serving integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE service_centres ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON service_centres TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON service_centres TO authenticated;

DROP POLICY IF EXISTS "Anyone can view service centres" ON service_centres;
CREATE POLICY "Anyone can view service centres" ON service_centres
FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Admins can manage service centres" ON service_centres;
CREATE POLICY "Admins can manage service centres" ON service_centres
FOR UPDATE TO authenticated USING (
  EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin')
) WITH CHECK (
  EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin')
);

