CREATE POLICY "Authenticated can view queue updates" ON queue_updates
FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "Admins can add queue updates" ON queue_updates;
CREATE POLICY "Admins can add queue updates" ON queue_updates
FOR INSERT TO authenticated WITH CHECK (
  EXISTS (SELECT 1 FROM profiles WHERE profiles.id = auth.uid() AND profiles.role = 'admin')
